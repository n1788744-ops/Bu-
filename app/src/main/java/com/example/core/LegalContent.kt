package com.example.core

enum class LegalDocumentType(val title: String) {
    PERSONAL_DATA("Согласие на обработку персональных данных"),
    PRIVACY_POLICY("Политика конфиденциальности"),
    LICENSE_AGREEMENT("Лицензионное соглашение"),
    ABOUT_ID_K("О системе авторизации ID K"),
}

object LegalContent {
    const val SUPPORT_EMAIL = "support@900.360org.ru"

    fun getBody(type: LegalDocumentType): String = when (type) {
        LegalDocumentType.PERSONAL_DATA -> """
            Настоящим я свободно, своей волей и в своём интересе даю согласие на обработку моих персональных данных в приложении «Браузер K» с использованием системы идентификации ID K.

            1. Перечень обрабатываемых данных:
            • Номер мобильного телефона и/или адрес электронной почты;
            • Имя, фамилия, отображаемый псевдоним, город, дата рождения и информация профиля, указанные пользователем самостоятельно;
            • Локальные настройки браузера, закладки и открытые вкладки.

            2. Цели обработки:
            • Регистрация и аутентификация учётной записи ID K;
            • Автоматическое создание и ведение профиля пользователя в браузере;
            • Обеспечение безопасной навигации и предупреждение о переходе на подозрительные ресурсы;
            • Техническая поддержка пользователей.

            3. Хранение и отзыв согласия:
            Данные хранятся локально на устройстве пользователя и используются исключительно для функционирования сервисов «Браузер K». Вы можете в любой момент изменить данные в разделе «Профиль ID K» или удалить учётную запись.

            По вопросам обработки и удаления персональных данных обращайтесь в службу поддержки: $SUPPORT_EMAIL
        """.trimIndent()

        LegalDocumentType.PRIVACY_POLICY -> """
            Политика конфиденциальности «Браузер K» и сервиса ID K

            1. Общие положения:
            Мы уважаем вашу приватность и стремимся обеспечить максимальную защиту данных при работе в сети Интернет.

            2. Какие данные сохраняются:
            • Регистрационные данные ID K (телефон или e-mail) и редактируемый профиль пользователя;
            • Журнал посещений и закладки браузера.

            3. Проверка безопасности ссылок:
            Анализ URL на признаки фишинга, небезопасного протокола HTTP, подозрительных доменов и IP-адресов выполняется локально на вашем устройстве без передачи истории посещений третьим лицам.

            4. Контакты службы поддержки:
            По всем вопросам конфиденциальности пишите на $SUPPORT_EMAIL
        """.trimIndent()

        LegalDocumentType.LICENSE_AGREEMENT -> """
            Лицензионное соглашение с конечным пользователем «Браузер K»

            1. Предмет соглашения:
            Правообладатель предоставляет Пользователю неисключительную лицензию на использование мобильного приложения «Браузер K» и системы входа ID K на территории всего мира.

            2. Права и обязанности:
            • Пользователь обязуется использовать функции браузера в соответствии с применимым законодательством;
            • Предупреждения о потенциально опасных ресурсах носят защитный характер; при нажатии кнопки «Всё равно перейти» Пользователь самостоятельно принимает риски посещения такого сайта.

            3. Отказ от гарантий:
            Приложение предоставляется на условиях «как есть». Разработчик обеспечивает стабильность встроенного интерфейса и регулярные обновления безопасности.

            4. Обратная связь и поддержка:
            Служба технической поддержки: $SUPPORT_EMAIL
        """.trimIndent()

        LegalDocumentType.ABOUT_ID_K -> """
            ID K — единый ключ для входа в «Браузер K» и персональные сервисы.

            • Быстрый вход по номеру телефона или электронной почте в привычном интерфейсе;
            • Автоматическое создание персонального профиля сразу после первой авторизации;
            • Полный контроль над личными данными, историей и закладками;
            • Встроенная защита от фишинга и подозрительных сайтов с возможностью осознанного перехода.

            Служба поддержки ID K: $SUPPORT_EMAIL
        """.trimIndent()
    }
}
